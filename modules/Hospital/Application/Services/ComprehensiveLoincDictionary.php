    /**
     * Menyemai (seed) parameter panel klinis standar ke dalam tabel database.
     */
    public static function seedStandardCatalog(): int
    {
        $panels = self::standardClinicalPanels();
        $seededCount = 0;

        foreach ($panels as $items) {
            foreach ($items as $item) {
                LaboratoryLoincCatalog::updateOrCreate(
                    ['loinc_num' => $item['loinc_num']],
                    [
                        'component' => $item['component'],
                        'property' => $item['property'],
                        'time_aspect' => $item['time_aspect'],
                        'system_specimen' => $item['system_specimen'],
                        'scale_type' => $item['scale_type'],
                        'method_type' => $item['method_type'],
                        'class_name' => $item['class_name'],
                        'reference_min' => $item['ref_min'],
                        'reference_max' => $item['ref_max'],
                        'unit' => $item['unit'],
                        'panic_low' => $item['panic_low'],
                        'panic_high' => $item['panic_high'],
                        'price_idr' => $item['price_idr'],
                        'is_orderable' => true,
                        'is_active' => true,
                    ]
                );
                $seededCount++;
            }
        }

        return $seededCount;
    }
