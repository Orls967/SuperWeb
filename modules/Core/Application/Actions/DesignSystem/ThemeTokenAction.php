<?php

declare(strict_types=1);

namespace Modules\Core\Application\Actions\DesignSystem;

use Illuminate\Support\Facades\File;
use Modules\Core\Domain\Exceptions\DesignSystem\TokenCycleException;
use Modules\Core\Domain\Exceptions\DesignSystem\UndefinedTokenException;
use Modules\Core\Domain\Models\DsToken;
use Modules\Shared\Domain\Algorithms\Ui\ThemeTokenResolver;

class ThemeTokenAction
{
    public function __construct(
        private readonly ?ThemeTokenResolver $resolver = null
    ) {}

    /**
     * Mendaftarkan atau memperbarui definisi token tema.
     */
    public function registerToken(
        string $theme,
        string $tokenName,
        string $tokenValue,
        int $version = 1,
        string $label = 'asumsi_simulasi'
    ): DsToken {
        return DsToken::updateOrCreate(
            [
                'theme' => strtolower(trim($theme)),
                'token_name' => trim($tokenName),
                'version' => $version,
            ],
            [
                'token_value' => trim($tokenValue),
                'label' => $label,
            ]
        );
    }

    /**
     * Mengompilasi token dari basis data ke resources/css/ds-tokens.css.
     *
     * @return array{file_path: string, lines_count: int, themes: list<string>}
     */
    public function buildCssFile(): array
    {
        $resolver = $this->resolver ?? new ThemeTokenResolver;
        $tokens = DsToken::latestVersion()->get();

        $themeDefinitions = [
            'light' => [],
            'dark' => [],
            'hc' => [],
        ];

        foreach ($tokens as $token) {
            $themeDefinitions[$token->theme][$token->token_name] = $token->token_value;
        }

        // Default fallback tokens bila database belum terisi lengkap
        $defaultTokens = [
            'light' => [
                'bg' => '#FFFFFF',
                'surface' => '#F8FAFC',
                'text' => '#111827',
                'text-muted' => '#6B7280',
                'primary' => '#1D4ED8',
                'onPrimary' => '{bg}',
                'border' => '#E2E8F0',
                'danger' => '#B91C1C',
                'muted' => '#9CA3AF',
            ],
            'dark' => [
                'bg' => '#0F172A',
                'surface' => '#1E293B',
                'text' => '#F1F5F9',
                'text-muted' => '#94A3B8',
                'primary' => '#93C5FD',
                'border' => '#334155',
                'muted' => '#94A3B8',
            ],
            'hc' => [
                'bg' => '#000000',
                'surface' => '#000000',
                'text' => '#FFFFFF',
                'text-muted' => '#FFFFFF',
                'border' => '#FFFFFF',
                'muted' => '{text}',
            ],
        ];

        foreach ($defaultTokens as $thm => $defs) {
            foreach ($defs as $k => $v) {
                if (! isset($themeDefinitions[$thm][$k])) {
                    $themeDefinitions[$thm][$k] = $v;
                }
            }
        }

        $cssBlocks = [];
        $cssBlocks[] = '/* Auto-generated by php artisan ds:tokens-build — Do not edit manually */';
        $cssBlocks[] = ':root, [data-theme="light"] {';

        $resolvedLight = $resolver->resolve($themeDefinitions, 'light');
        if ($resolvedLight['status'] === ThemeTokenResolver::STATUS_CYCLE) {
            throw new TokenCycleException(implode(', ', $resolvedLight['errors']));
        }
        if ($resolvedLight['status'] === ThemeTokenResolver::STATUS_UNDEFINED) {
            throw new UndefinedTokenException(implode(', ', $resolvedLight['errors']));
        }

        foreach ($resolvedLight['tokens'] as $name => $val) {
            $cssVarName = str_replace(['.', '_'], '-', $name);
            if (str_starts_with($cssVarName, 'color-')) {
                $cssVarName = substr($cssVarName, 6);
            }
            $cssBlocks[] = "    --color-{$cssVarName}: {$val};";
        }
        $cssBlocks[] = '}';
        $cssBlocks[] = '';

        foreach (['dark', 'hc'] as $theme) {
            $resolved = $resolver->resolve($themeDefinitions, $theme);
            if ($resolved['status'] === ThemeTokenResolver::STATUS_CYCLE) {
                throw new TokenCycleException(implode(', ', $resolved['errors']));
            }
            if ($resolved['status'] === ThemeTokenResolver::STATUS_UNDEFINED) {
                throw new UndefinedTokenException(implode(', ', $resolved['errors']));
            }

            $cssBlocks[] = "[data-theme=\"{$theme}\"] {";
            foreach ($resolved['tokens'] as $name => $val) {
                $cssVarName = str_replace(['.', '_'], '-', $name);
                if (str_starts_with($cssVarName, 'color-')) {
                    $cssVarName = substr($cssVarName, 6);
                }
                $cssBlocks[] = "    --color-{$cssVarName}: {$val};";
            }
            $cssBlocks[] = '}';
            $cssBlocks[] = '';
        }

        $cssContent = implode("\n", $cssBlocks)."\n";
        $filePath = base_path('resources/css/ds-tokens.css');
        File::ensureDirectoryExists(dirname($filePath));
        File::put($filePath, $cssContent);

        return [
            'file_path' => $filePath,
            'lines_count' => count($cssBlocks),
            'themes' => ['light', 'dark', 'hc'],
        ];
    }
}
